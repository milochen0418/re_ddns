#!/usr/bin/env python3
"""Regenerate docs/site/apps.js from data/appstore_catalog.json.

    python3 docs/site/update_apps.py            # rewrite apps.js
    python3 docs/site/update_apps.py --check    # exit 1 if apps.js is out of date

The website (docs/index.html) reads apps.js, so its app list follows the catalog.
Per app it takes: name, subdomain, icon, github_repo, description (English and
zh-Hant), storage collections and whether settings are required at install.

Optional card picture: docs/site/img/apps/<subdomain>.webp (a card without one
shows its icon). Icons: docs/site/icons/<icon>.svg (Lucide); an icon named in
the catalog but missing there falls back to box.svg with a warning.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SITE = ROOT / "docs" / "site"
CATALOG = ROOT / "data" / "appstore_catalog.json"
OUT = SITE / "apps.js"

# Category per subdomain; anything not listed lands in "tools".
CATEGORIES = {
    "ai": ["ai"],
    "create": ["md", "plantuml", "vecdraw", "cad", "cad-roam", "cellora", "chipova", "grid"],
    "health": ["dicom-data-explorer", "dicom-viewer", "pacs-lab"],
    "meet": ["relack", "audio-chat", "livekit", "video-chat", "avatar-chat",
             "english-chat", "nooklane"],
    "play": ["mindspar", "snake-duel", "apexline"],
}
CAT_OF = {sub: cat for cat, subs in CATEGORIES.items() for sub in subs}
AI_RE = re.compile(r"\bAI\b|\bLLM\b|Ollama|Claude")
# Apps whose code offers tools to AI agents through the AI Hub although their
# catalog description does not mention AI.
AI_EXTRA = {"cad", "cad-roam", "grid"}


def icon_svg(name: str) -> str:
    path = SITE / "icons" / f"{name}.svg"
    if not path.exists():
        print(f"warning: no icon {name}.svg, using box.svg. Get it with:\n"
              f"  curl -o docs/site/icons/{name}.svg https://unpkg.com/lucide-static@1.64.0/icons/{name}.svg",
              file=sys.stderr)
        path = SITE / "icons" / "box.svg"
    svg = path.read_text(encoding="utf-8")
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    svg = re.sub(r'\s(width|height)="24"', "", svg)
    svg = re.sub(r"\s+", " ", svg).replace("> <", "><").strip()
    return svg


def build() -> tuple[str, int, int]:
    catalog = json.loads(CATALOG.read_text(encoding="utf-8"))
    apps = []
    for entry in catalog["apps"]:
        sub = entry["subdomain"]
        repo = entry.get("github_repo", "").removesuffix(".git")
        zh = (entry.get("i18n") or {}).get("zh-Hant") or {}
        img = SITE / "img" / "apps" / f"{sub}.webp"
        apps.append({
            "id": entry["id"],
            "name": entry["name"],
            "sub": sub,
            "cat": CAT_OF.get(sub, "tools"),
            "repo": repo,
            "icon": icon_svg(entry.get("icon") or "box"),
            "desc": {"en": entry.get("description", ""),
                     "zh": zh.get("description") or entry.get("description", "")},
            "img": f"site/img/apps/{sub}.webp" if img.exists() else None,
            "collections": [s["collection"] for s in entry.get("storage") or []],
            "ai": sub in AI_EXTRA or bool(AI_RE.search(entry.get("description", ""))),
            "setup": any(e.get("required") for e in entry.get("env_schema") or []),
        })
    meta = {
        "count": len(apps),
        "categories": list(CATEGORIES) + ["tools"],
    }
    body = (
        "// Generated by docs/site/update_apps.py from data/appstore_catalog.json. Do not edit by hand.\n"
        f"window.AAS_META = {json.dumps(meta, ensure_ascii=False)};\n"
        f"window.AAS_APPS = {json.dumps(apps, ensure_ascii=False, indent=1)};\n"
    )
    return body, len(apps), sum(1 for a in apps if a["img"])


def main() -> None:
    body, count, with_img = build()
    if "--check" in sys.argv[1:]:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != body:
            sys.exit(f"{OUT.relative_to(ROOT)} is out of date: run python3 docs/site/update_apps.py")
        print(f"{OUT.relative_to(ROOT)} is up to date ({count} apps)")
        return
    OUT.write_text(body, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {count} apps, {with_img} with pictures")


if __name__ == "__main__":
    main()
